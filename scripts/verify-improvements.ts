import assert from "node:assert/strict";
import { blankPlayer, LINEUP, type Deck } from "../src/lib/deck";
import { calcDeckTotal, deckPlayerResults, skillScore } from "../src/lib/engine";
import { NEW_SKILLS, expectedScore, trialProbability } from "../src/lib/skillUpdates";
import { bindRank, findRankTarget, rankingNameKey } from "../src/lib/rankSubmit";
import type { PublicRank } from "../src/lib/supabase";

const tables = { overrides: {}, customs: [] };
const d: Deck = { id: "new", name: " My   Deck ", updatedAt: 1,
  players: LINEUP.map(p => blankPlayer(p.row, p.kind, p.pos, p.order)),
  chem: { commander: "X", catcher: "X", pitchChem: "X", batChem: "X", wbcP: "X", wbcB: "X" }, flags: {}, yearInputs: {} };
const result = () => deckPlayerResults(d, tables)[0];
const p = d.players[0];
p.name = "선수";
p.base = [100, 100, 100];
assert.deepEqual(result().auto, [103, 103, 103]);
assert.equal(Math.round(result().ability * 100) / 100, 247.2);
p.train[0] = 10;
assert.equal(result().final[0], 113);
p.finalOv[0] = 150;
p.train[0] = 20;
assert.equal(result().final[0], 150);
p.finalOv[0] = "";
assert.equal(result().final[0], 123);
p.leaderBonus = [2, 3, 1];
assert.deepEqual(result().auto, [125, 106, 104]);
p.blackPos = [8, 8, 8];
p.card = "시그니처";
assert.equal(result().auto[0], 125);
p.card = "시그니처 블랙";
assert.equal(result().auto[0], 133);
p.skills = ["[S0] WAR 리더", "잘못된 스킬명", "", ""];
assert.equal(result().skill, null);
assert.ok(Math.abs(result().total - result().ability - 35.7) < 1e-9);
assert.ok(result().warnings.some(w => w.includes("임시")));
assert.equal(skillScore("batter", " [Ｓ0] WAR\u200b 리더 ", tables), 35.7);
assert.equal(skillScore("batter", "[S0] 리틀빅맨(좌타X+2번O)", tables), 33.3);
assert.equal(skillScore("batter", "[S0] 리틀빅맨(좌타X+2번Q)", tables), null);
assert.equal(skillScore("pitcher", "[S0] WAR 리더", tables), 35.55);
assert.equal(skillScore("pitcher", "[S2] 레버리지 릴리퍼 (3아웃 이전)", tables), 53.6);
assert.equal(skillScore("pitcher", "[S2] 승리 공식 (동점·리드)", tables), 52.35);
assert.equal(skillScore("pitcher", "[S2] 컴백 플래그 (동점·지고 있음)", tables), 47);
assert.equal(skillScore("pitcher", "[S4] 신속한 처리 (20아웃 처리)", tables), 4.7);
const sp = d.players[9]; sp.skills[0] = "[S0] 신속한 처리 (0아웃 처리)";
assert.equal(deckPlayerResults(d, tables)[9].skill, 0);
const rp = d.players[14]; rp.skills[0] = sp.skills[0];
assert.equal(deckPlayerResults(d, tables)[14].skill, 32.9);
assert.equal(new Set(NEW_SKILLS.map(s => `${s.kind}:${s.name}`)).size, NEW_SKILLS.length);
assert.equal(calcDeckTotal(d, tables).named, 1);
assert.equal(expectedScore(10, 30, 25), 15);
assert.equal(expectedScore(10, 30, 0), 10);
assert.equal(expectedScore(10, 30, 100), 30);
assert.ok(Number.isNaN(expectedScore(10, 30, -1)));
assert.equal(trialProbability(100, 0)?.atLeastOne, 0);
assert.equal(trialProbability(100, 1)?.atLeastOne, 1);
assert.equal(trialProbability(0, 100)?.meanTrials, Infinity);
assert.equal(trialProbability(10, 1.5), null);
assert.ok(Math.abs(trialProbability(10, 2)!.atLeastOne - 0.19) < 1e-12);
const old = { ...d, id: "old", name: "my deck" };
const links = { r1: { token: "secret", deckId: old.id } };
assert.equal(rankingNameKey(d.name), "my deck");
assert.equal(findRankTarget(d, [old, d], links, [])?.[0], "r1");
const rows = [{ id: "someone-else", deck_name: "my deck" }] as PublicRank[];
assert.equal(findRankTarget(d, [d], {}, rows), undefined);
assert.equal(findRankTarget(d, [d], { r2: { owned: true, deckId: "" } }, [{ id: "r2", deck_name: "MY DECK" }] as PublicRank[])?.[0], "r2");
const rebound = bindRank(links, "r1", d.id, { token: "secret" }, "sig");
assert.equal(rebound.r1.deckId, d.id);
assert.equal(links.r1.deckId, "old");
console.log("improvement regression checks passed");

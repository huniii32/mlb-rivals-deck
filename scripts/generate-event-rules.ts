import fs from "node:fs";
import {
  availableSkills,
  skillId,
  type DrawSkill,
} from "../src/lib/skillSimulator";
import { SETTINGS, EVALUATOR } from "../src/demo/eventModel";
import { ROSTER, themeLabel } from "../src/lib/combinationRoster";
import { HOF_PLAYERS } from "../src/lib/hofRecruitment";

// Freeze the official pools and unmodified S-level score table for this event.
const rules = {
  settings: SETTINGS,
  skills: availableSkills(SETTINGS).map((skill) => {
    const evaluated = EVALUATOR.evaluate({
      ...skill,
      id: skillId(skill),
      level: "S",
    } as DrawSkill);
    if (evaluated.score === null)
      throw Error(`Missing event score: ${skill.name}`);
    return {
      id: skillId(skill),
      name: skill.name,
      tier: skill.tier,
      weight: skill.rates.reduce((a, b) => a + b, 0),
      score: evaluated.score,
      basis: evaluated.basis,
    };
  }),
  moment: ROSTER.map((p) => ({
    id: p.id,
    name: p.name,
    team: p.team,
    grade: p.grade,
    theme: themeLabel(p.theme),
  })),
  hof: HOF_PLAYERS,
};
const data = JSON.stringify(rules).replace(/'/g, "''");
fs.writeFileSync(
  "scripts/event-rules-v1.sql",
  `-- Generated by scripts/generate-event-rules.ts. Never replace a live event's rules.\ninsert into public.sim_event_rules(id, data) values ('coffee-sp-s-v1', '${data}'::jsonb) on conflict (id) do nothing;\n`,
);
console.log(
  `Frozen event rules: ${rules.skills.length} skills, ${rules.moment.length} moment cards, ${rules.hof.length} HOF players.`,
);
